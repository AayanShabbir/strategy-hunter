def _eval(node: dict, panel: dict) -> pd.DataFrame:
    t = node["node_type"]
    if t == "feature":
        return panel[node["feature_name"]].astype(float)
    op, args = node["operator"], node["arguments"]
    if op == "TsStd":
        x = _eval(args[0], panel)
        return x.where(np.isfinite(x)).rolling(args[1]["lookback_window"]).std(ddof=1)
    with np.errstate(all="ignore"):
        if op == "Log":
            return np.log(_eval(args[0], panel).abs() + EPS)
        a, b = _eval(args[0], panel), _eval(args[1], panel)
        if op == "Add":
            return a + b
        if op == "Sub":
            return a - b
        if op == "Div":
            s = np.sign(b).replace(0, 1.0)
            return a / (b + s * EPS)
    raise ValueError("unsupported operator " + str(op))


def compute_signal(panel: dict, member=None) -> pd.DataFrame:
    """Sign-oriented cross-sectional z-score of the formula per day (NaN where the day has < 30 tradable assets)."""
    F = _eval(AST, panel).to_numpy(dtype=float)
    F = np.where(np.isfinite(F) & (np.abs(F) < 1e150), F, np.nan)
    c, v = panel["$close"].to_numpy(float), panel["$volume"].to_numpy(float)
    ok = np.isfinite(c) & (c > 0) & np.isfinite(v) & (v > 0) & np.isfinite(F)
    if member is not None:
        ok &= np.asarray(member, bool)
    n = ok.sum(1)
    mu = np.where(ok, F, 0.0).sum(1) / np.maximum(n, 1)
    cen = np.where(ok, F - mu[:, None], 0.0)
    sd = np.sqrt((cen * cen).sum(1) / np.maximum(n - 1, 1))
    good = (n >= MIN_CROSS_SECTION) & (sd > 1e-12)
    z = np.full(F.shape, np.nan)
    z[good] = np.where(ok[good], cen[good] / sd[good][:, None], np.nan)
    return pd.DataFrame(SIGN * z, index=panel["$close"].index, columns=panel["$close"].columns)


def target_weights(signal: pd.DataFrame) -> pd.DataFrame:
    """Dollar-neutral weights with sum|w| = 1 on each day with a valid cross-section."""
    s = signal.to_numpy(float)
    ok = np.isfinite(s)
    n = ok.sum(1)
    c = np.where(ok, s - (np.where(ok, s, 0.0).sum(1) / np.maximum(n, 1))[:, None], 0.0)
    g = np.abs(c).sum(1)
    w = np.where((g > 1e-12)[:, None], c / np.where(g > 1e-12, g, 1.0)[:, None], 0.0)
    return pd.DataFrame(w, index=signal.index, columns=signal.columns)


def backtest(weights: pd.DataFrame, close: pd.DataFrame, cost_bps: float = 5.0) -> pd.Series:
    """Net daily return of weights set at each close (earned next day), one-way cost in bp on traded notional."""
    r = (close.shift(-1) / close - 1.0).replace([np.inf, -np.inf], np.nan).fillna(0.0).iloc[:-1]
    W = weights.iloc[:-1]
    gross = (W * r).sum(axis=1)
    pre = (W.shift(1) * (1.0 + r.shift(1))).div(1.0 + gross.shift(1), axis=0).fillna(0.0)
    turnover = (W - pre).abs().sum(axis=1)
    return (gross - cost_bps * 1e-4 * turnover).rename(AST_HASH)


