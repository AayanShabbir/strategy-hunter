"""Writes docs/data_quality_sp500.md and docs/data/sp500_merged_provenance.json (tickers, dates, counts only; no prices).
Run:  PYTHONPATH=. .venv17/bin/python -m src.data.dq_report            (search window 2009..2020; never touches 2021+)"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
from src.data import sp500_pit as P
from src.data import multisource as M

ROOT = Path(__file__).resolve().parents[2]
BASELINE = {"removed_names": 240, "removed_names_priced": 62, "member_day_coverage": 0.749}   # measured with load_sp500_pit earlier


def agreement_summary(rows):
    import pandas as pd
    d = pd.DataFrame(rows)
    if d.empty: return {"tickers": 0}
    return {"tickers": int(len(d)), "ret_corr_median": round(float(d.ret_corr.median()), 5), "ret_corr_p10": round(float(d.ret_corr.quantile(.1)), 4),
            "frac_mad_lt_1pct": round(float((d.mad < 0.01).mean()), 3), "frac_ret_corr_ge_0.98": round(float((d.ret_corr >= 0.98).mean()), 3),
            "frac_abs_median_offset_lt_2pct": round(float((d.median_log_ratio.abs() < 0.02).mean()), 3),
            "frac_volume_within_10pct": round(float((d.vol_log_ratio.abs() < 0.1).mean()), 3)}


def build(cache: bool = True) -> dict:
    import pandas as pd
    win, yf, al, fs = M.gather_search_sources(cache)
    frames, prov, dates = M.merge_sources(win, yf, al, P.W0, P.W1, P.START, M.SEARCH_END, fs=fs)
    cov = M.coverage_numbers(win, frames, prov, P.W0, P.W1, dates)
    pan = M.panel_from_merge(frames, prov, win, P.W0, P.W1, {"coverage": cov})
    d = pd.DatetimeIndex(pan.dates); by_year = {}
    pit_days = {}
    for y in range(2010, 2021):
        yy = (d.year == y); by_year[y] = round(float(pan.member[yy].sum(1).mean()), 1)
        pit_days[y] = round(float(P.membership_mask(d[yy], pan.assets + [], win, f"{y}-01-01", f"{y}-12-31").sum(1).mean()), 1)
    # PIT member count per year including unpriced names
    allm = {}
    for y in range(2010, 2021):
        yy = d[d.year == y]; tot = 0
        for r in win.itertuples():
            m = (yy >= r.start_date)
            if not pd.isna(r.end_date): m &= yy < r.end_date
            tot += int(m.sum())
        allm[y] = round(tot / max(len(yy), 1), 1)
    agree = {"yfinance_vs_finsaber_2010_2020": agreement_summary(M.pair_agreement(yf, fs, "2010-01-01", "2020-12-31")),
             "yfinance_vs_alpaca_2016_2020": agreement_summary(M.pair_agreement(yf, al, "2016-01-01", "2020-12-31")),
             "alpaca_vs_finsaber_2016_2020": agreement_summary(M.pair_agreement(al, fs, "2016-01-01", "2020-12-31"))}
    dropped = {t: r["reason"] for t, r in prov.items() if r["status"] == "dropped" and r["member_days"] > 0}
    return {"coverage": cov, "baseline": BASELINE, "usable_members_per_day": by_year, "pit_members_per_day": allm, "agreement": agree,
            "dropped_with_member_days": dropped, "provenance": prov}


def write(r: dict) -> None:
    (ROOT / "docs" / "data").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "data" / "sp500_merged_provenance.json").write_text(json.dumps({"coverage": r["coverage"], "tickers": r["provenance"]}, indent=0, sort_keys=True))
    c, b = r["coverage"], r["baseline"]
    pv = [v for v in r["provenance"].values() if v["status"] == "kept"]
    n_fin = sum(1 for v in pv if v["sources_used"] == ["finsaber"]); n_alp = sum(1 for v in pv if v["sources_used"] == ["alpaca"])
    L = ["# S&P 500 data quality: survivorship coverage with free sources", "",
         "Generated by `python -m src.data.dq_report` (search window 2009-01-01 .. 2020-12-31; no 2021+ data is read). Per-ticker provenance (tickers, dates,",
         "counts, QC numbers; no prices) is in [`docs/data/sp500_merged_provenance.json`](data/sp500_merged_provenance.json).", "",
         "## Headline: baseline vs merged loader", "",
         "| metric (PIT membership 2010-2020, MIT `fja05680/sp500` windows) | old `load_sp500_pit` (yfinance only) | `load_sp500_merged` |", "|---|---|---|",
         f"| PIT member-days with prices | {b['member_day_coverage']:.1%} | **{c['member_day_coverage']:.1%}** ({c['member_days_priced']:,} of {c['member_days_total']:,}) |",
         f"| names removed 2010-2020 that have prices | {b['removed_names_priced']} of {b['removed_names']} ({b['removed_names_priced'] / b['removed_names']:.0%}) | **{c['removed_names_priced']} of {c['removed_names']} ({c['removed_name_coverage']:.0%})** |",
         f"| member-days of removed names that are priced | n/a (not measured before) | {c['removed_member_day_coverage']:.1%} |",
         f"| PIT names with any price | 497 of 738 | {c['pit_names_priced']} of {c['pit_names']} |", "",
         "Usable members per trading day (average over the year) vs the true PIT count:", "",
         "| year | PIT members | usable (merged) | share |", "|---|---|---|---|"]
    for y in sorted(r["usable_members_per_day"]):
        u, p = r["usable_members_per_day"][y], r["pit_members_per_day"][y]
        L.append(f"| {y} | {p} | {u} | {u / p:.1%} |")
    L += ["", "## Sources tried", "",
          "| source | result |", "|---|---|",
          "| yfinance (primary, as before) | adjusted OHLCV for survivors only; no history for most delisted/renamed names |",
          "| yfinance alternate tickers (`ALT_TICKERS`: FB->META, ANTM->ELV, UTX->RTX, ...) | Used only when an overlap check against another source passes; a few pre-2016 renamed names recovered; unvalidatable mappings (e.g. JEC->J) are not used |",
          "| Alpaca Market Data v2 (paper keys, read-only data endpoint) | SIP daily bars for delisted symbols **from 2016-01-04**; covers 2016+ for almost every PIT name, nothing before 2016 |",
          "| FINSABER-reproduce on Hugging Face (Apache-2.0, `all_sp500_prices_2000_2024_delisted_include.csv`, SHA-256 pinned) | 2000-2024 OHLCV + adjusted close for 1,017 symbols incl. delisted S&P names; **this is what lifts 2010-2015 coverage**; upstream quote provenance is not stated, so it is cross-checked below |",
          "| Stooq | not usable: the endpoint serves a JavaScript proof-of-work page to non-browser clients; not circumvented |",
          "| Tiingo free tier | not tried: needs an account/API token the box does not have |",
          "| SEC EDGAR | filings and corporate-action text only, no price series |",
          "| `vendor/` | only `pypbo` (a statistics package); no price data |", "",
          "## Cross-source agreement (evidence for trusting the merged series)", "",
          "Per ticker on the overlap of two sources: constant offset of log price (adjustment basis), MAD of the log ratio, daily-return correlation, volume ratio.", "",
          "| pair | tickers | median ret-corr | 10th pct ret-corr | share MAD<1% | share corr>=0.98 | share volume within 10% |", "|---|---|---|---|---|---|---|"]
    for k, a in r["agreement"].items():
        if a.get("tickers"): L.append(f"| {k} | {a['tickers']} | {a['ret_corr_median']} | {a['ret_corr_p10']} | {a['frac_mad_lt_1pct']} | {a['frac_ret_corr_ge_0.98']} | {a['frac_volume_within_10pct']} |")
    L += ["", "Tickers that disagree (re-used symbols such as KG, PX, PARA, KDP; spin-off/merger basis jumps) fail the overlap test (MAD<1% and return corr>=0.98)",
          "and are never spliced; the merge then takes the single best source instead.", "",
          "## What this does NOT fix", "",
          f"* {len(r['dropped_with_member_days'])} PIT names with member-days still have no usable price (listed below). They are mostly names that left before 2016 and are absent from every free source tried, plus re-used tickers whose only price history belongs to a different company.",
          f"* {n_fin} names are priced by FINSABER alone and {n_alp} by Alpaca alone (no second source can check them); FINSABER series carry an integrity check (no |daily log return| > 1.2, no stale series, no bad bars).",
          "* Prices are adjusted closes on the fetch-date basis; sources differ by a constant factor which the merge removes by rescaling on the overlap (recorded as `scale` per ticker).",
          f"* Volume agrees within 10% for {r['agreement']['yfinance_vs_finsaber_2010_2020']['frac_volume_within_10pct']:.0%} of yfinance/FINSABER tickers but only {r['agreement']['yfinance_vs_alpaca_2016_2020']['frac_volume_within_10pct']:.0%} of yfinance/Alpaca tickers (volume-based formulas on Alpaca-only names are less reliable).",
          "* Membership comes from a community dataset (MIT) and is not S&P's own file; ticker-level only (a company that changed ticker appears as two names).",
          "* The old `load_sp500` and `load_sp500_pit` are unchanged and reproducible; SDE runs and committed results use them, not this loader.", "",
          "## Names with member-days that stay unpriced", "", ", ".join(f"{t} ({v})" for t, v in sorted(r["dropped_with_member_days"].items())), ""]
    (ROOT / "docs" / "data_quality_sp500.md").write_text("\n".join(L))


if __name__ == "__main__":
    r = build(); write(r); print(json.dumps({k: r[k] for k in ("coverage", "usable_members_per_day", "agreement")}, indent=1))
